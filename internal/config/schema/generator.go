func Generate() ([]byte, error) {
	schemaDoc, err := jsonschema.For[ralphconfig.Config](nil)
	if err != nil {
		return nil, fmt.Errorf("infer config schema: %w", err)
	}
	schemaDoc.Comment = GeneratedComment

	rawSchema, err := json.Marshal(schemaDoc)
	if err != nil {
		return nil, fmt.Errorf("marshal inferred schema: %w", err)
	}

	var root map[string]any
	if err := json.Unmarshal(rawSchema, &root); err != nil {
		return nil, fmt.Errorf("decode inferred schema: %w", err)
	}

	if err := applyRuntimeConstraints(root); err != nil {
		return nil, fmt.Errorf("apply runtime constraints: %w", err)
	}

	output, err := json.MarshalIndent(root, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshal schema: %w", err)
	}
	return append(output, '\n'), nil
}

func WriteRoot(root string) error {
	output, err := Generate()
	if err != nil {
		return fmt.Errorf("generate schema: %w", err)
	}
	path := filepath.Join(root, ArtifactPath)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("create schema directory: %w", err)
	}
	if err := os.WriteFile(path, output, artifactFileMode); err != nil {
		return fmt.Errorf("write schema file %q: %w", path, err)
	}
	return nil
}

func applyRuntimeConstraints(root map[string]any) error {
	for _, patch := range runtimeConstraintPatches {
		target, err := objectAtPath(root, patch.path)
		if err != nil {
			return fmt.Errorf("%s: %w", patch.name, err)
		}
		patch.apply(target)
	}

	applyAdditionalPropertiesFalse(root)
	return nil
}

func objectAtPath(root map[string]any, path []string) (map[string]any, error) {
	current := any(root)
	for _, key := range path {
		node, ok := current.(map[string]any)
		if !ok {
			return nil, fmt.Errorf("segment %q: %w", key, errNotObject)
		}
		next, ok := node[key]
		if !ok {
			return nil, fmt.Errorf("missing key %q: %w", key, errKeyNotFound)
		}
		current = next
	}

	target, ok := current.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("path %q: %w", strings.Join(path, "."), errNotObject)
	}
	return target, nil
}

func setEnum(target map[string]any, values ...string) {
	enum := make([]any, 0, len(values))
	for _, value := range values {
		enum = append(enum, value)
	}
	target["enum"] = enum
}

