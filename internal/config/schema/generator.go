func applyAdditionalPropertiesFalse(node any) {
	schema, ok := node.(map[string]any)
	if !ok {
		return
	}

	if includesObjectType(schema["type"]) {
		schema["additionalProperties"] = false
	}

	if properties, ok := schema["properties"].(map[string]any); ok {
		for _, child := range properties {
			applyAdditionalPropertiesFalse(child)
		}
	}

	switch items := schema["items"].(type) {
	case map[string]any:
		applyAdditionalPropertiesFalse(items)
	case []any:
		for _, child := range items {
			applyAdditionalPropertiesFalse(child)
		}
	}

	for _, key := range []string{"oneOf", "anyOf", "allOf"} {
		options, ok := schema[key].([]any)
		if !ok {
			continue
		}
		for _, option := range options {
			applyAdditionalPropertiesFalse(option)
		}
	}
}

func includesObjectType(typeValue any) bool {
	switch typed := typeValue.(type) {
	case string:
		return typed == "object"
	case []any:
		for _, value := range typed {
			if typeName, ok := value.(string); ok && typeName == "object" {
				return true
			}
		}
	}
	return false
}
